from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

from opst.evaluation import (
    DEFAULT_ALGORITHMS,
    run_manifest,
    run_manifest_instrumented,
    write_jsonl,
    write_parquet,
    write_results_csv,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run OP-ST algorithms on an instance manifest.")
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("data/instances/smoke/manifest.csv"),
        help="Instance manifest CSV generated by scripts/generate_instances.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("results/raw/smoke_results.csv"),
        help="Output tidy result CSV.",
    )
    parser.add_argument("--run-id", default="smoke")
    parser.add_argument(
        "--algorithms",
        nargs="+",
        default=list(DEFAULT_ALGORITHMS),
        choices=list(DEFAULT_ALGORITHMS),
    )
    parser.add_argument(
        "--instrument",
        action="store_true",
        help="Write solution JSONL and split trace parquet files.",
    )
    parser.add_argument(
        "--solutions-output",
        type=Path,
        default=Path("results/raw/exact_suite_solutions.jsonl"),
    )
    parser.add_argument(
        "--split-trace-output",
        type=Path,
        default=Path("results/raw/exact_suite_split_trace.parquet"),
    )
    parser.add_argument(
        "--compact-trace-output",
        type=Path,
        default=Path("results/raw/exact_suite_compact_candidate_trace.parquet"),
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    start = datetime.now(timezone.utc)
    if args.instrument:
        rows, solution_records, alpha_trace_rows, compact_trace_rows = run_manifest_instrumented(
            args.manifest,
            run_id=args.run_id,
            algorithm_names=tuple(args.algorithms),
        )
        write_jsonl(solution_records, args.solutions_output)
        write_parquet(alpha_trace_rows, args.split_trace_output)
        write_parquet(compact_trace_rows, args.compact_trace_output)
    else:
        rows = run_manifest(
            args.manifest,
            run_id=args.run_id,
            algorithm_names=tuple(args.algorithms),
        )
        solution_records = []
        alpha_trace_rows = []
        compact_trace_rows = []
    write_results_csv(rows, args.output)
    end = datetime.now(timezone.utc)
    manifest_path = Path("results/manifests") / f"{args.run_id}_run_manifest.json"
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(
        json.dumps(
            {
                "run_id": args.run_id,
                "input_manifest": str(args.manifest),
                "output_results": str(args.output),
                "algorithms": args.algorithms,
                "row_count": len(rows),
                "error_count": sum(1 for row in rows if row["status"] == "error"),
                "solution_record_count": len(solution_records),
                "split_trace_count": len(alpha_trace_rows),
                "compact_candidate_trace_count": len(compact_trace_rows),
                "solutions_output": str(args.solutions_output) if args.instrument else "",
                "split_trace_output": str(args.split_trace_output) if args.instrument else "",
                "compact_trace_output": str(args.compact_trace_output) if args.instrument else "",
                "started_at_utc": start.isoformat(),
                "ended_at_utc": end.isoformat(),
            },
            indent=2,
            sort_keys=True,
        ),
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} rows to {args.output}")
    print(f"Run manifest: {manifest_path}")


if __name__ == "__main__":
    main()
