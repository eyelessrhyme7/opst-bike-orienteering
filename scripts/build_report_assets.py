from __future__ import annotations

import argparse
from pathlib import Path

from opst.reporting import (
    paired_ablations,
    plot_reward_ratio_boxplot,
    read_result_rows,
    summarize_by_algorithm,
    write_markdown_summary,
    write_rows,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build report assets from saved result rows.")
    parser.add_argument(
        "--results",
        type=Path,
        default=Path("results/raw/smoke_results.csv"),
        help="Input result CSV generated by scripts/run_experiments.py.",
    )
    parser.add_argument("--tables-dir", type=Path, default=Path("results/tables"))
    parser.add_argument("--figures-dir", type=Path, default=Path("results/figures"))
    parser.add_argument("--prefix", default="smoke", help="Filename prefix for generated assets.")
    parser.add_argument(
        "--summary-md",
        type=Path,
        default=Path("results/RESULTS_SUMMARY.md"),
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    rows = read_result_rows(args.results)
    summaries = summarize_by_algorithm(rows)
    ablations = paired_ablations(rows)

    summary_path = args.tables_dir / f"{args.prefix}_core_summary.csv"
    ablation_path = args.tables_dir / f"{args.prefix}_paired_ablations.csv"
    figure_path = args.figures_dir / f"{args.prefix}_reward_ratio_boxplot.png"

    write_rows(summary_path, summaries)
    write_rows(ablation_path, ablations)
    plot_reward_ratio_boxplot(rows, figure_path)
    write_markdown_summary(args.summary_md, summaries, row_count=len(rows))

    print(f"Wrote {summary_path}")
    print(f"Wrote {ablation_path}")
    print(f"Wrote {figure_path}")
    print(f"Wrote {args.summary_md}")


if __name__ == "__main__":
    main()
